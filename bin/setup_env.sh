#!/usr/bin/env bash
# Prompts for production env vars and writes env/.env.
set -euo pipefail

ENV_FILE="env/.env"

# ── helpers ──────────────────────────────────────────────────────────────────

prompt() {
    local label="$1" var="$2" default="${3:-}" secret="${4:-}"
    local value=""
    while [[ -z "$value" ]]; do
        if [[ -n "$default" ]]; then
            printf "%s [%s]: " "$label" "$default"
        else
            printf "%s: " "$label"
        fi
        if [[ "$secret" == "secret" ]]; then
            read -rs value; echo
        else
            read -r value
        fi
        value="${value:-$default}"
        if [[ -z "$value" ]]; then
            echo "  (required — please enter a value)"
        fi
    done
    printf -v "$var" '%s' "$value"
}

prompt_optional() {
    local label="$1" var="$2" default="${3:-}"
    printf "%s [%s]: " "$label" "$default"
    read -r value
    printf -v "$var" '%s' "${value:-$default}"
}

# ── guard: overwrite? ─────────────────────────────────────────────────────────

if [[ -f "$ENV_FILE" ]]; then
    printf "\n%s already exists. Overwrite? [y/N]: " "$ENV_FILE"
    read -r confirm
    [[ "$confirm" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 0; }
fi

mkdir -p env

# ── collect values ────────────────────────────────────────────────────────────

echo ""
echo "=== cosound production environment setup ==="
echo "Press Enter to accept a [default]. Required fields cannot be left blank."
echo ""

# Secret key — offer to auto-generate
printf "SECRET_KEY — generate automatically? [Y/n]: "
read -r sk_choice
if [[ "$sk_choice" =~ ^[Nn]$ ]]; then
    prompt "SECRET_KEY" SECRET_KEY "" secret
else
    SECRET_KEY=$(python3 -c "import secrets; print(secrets.token_urlsafe(64))")
    echo "  Generated."
fi

SITE_ADDRESS="cosound.ca, www.cosound.ca"
PROD_HOSTS="cosound.ca,www.cosound.ca"

echo ""
echo "--- Postgres ---"
prompt_optional "POSTGRES_USER" POSTGRES_USER "cosound"
prompt_optional "POSTGRES_DB"   POSTGRES_DB   "cosound"
prompt          "POSTGRES_PASSWORD" POSTGRES_PASSWORD "" secret
# Confirm password
while true; do
    printf "Confirm POSTGRES_PASSWORD: "
    read -rs pg_confirm; echo
    [[ "$pg_confirm" == "$POSTGRES_PASSWORD" ]] && break
    echo "  Passwords do not match — try again."
done
DATABASE_URL="postgres://${POSTGRES_USER}:${POSTGRES_PASSWORD}@db:5432/${POSTGRES_DB}"

echo ""
echo "--- AWS ---"
prompt "AWS_ACCESS_KEY_ID"     AWS_ACCESS_KEY_ID
prompt "AWS_SECRET_ACCESS_KEY" AWS_SECRET_ACCESS_KEY "" secret
prompt_optional "AWS_STORAGE_BUCKET_NAME" AWS_STORAGE_BUCKET_NAME "cosounds-frishkopf"
prompt_optional "AWS_S3_REGION_NAME"      AWS_S3_REGION_NAME      "us-east-2"

echo ""
echo "--- First admin (optional bootstrap) ---"
prompt_optional "FIRST_ADMIN_EMAIL"    FIRST_ADMIN_EMAIL    "admin@cosound.ca"
prompt_optional "FIRST_ADMIN_USERNAME" FIRST_ADMIN_USERNAME "admin"
prompt          "FIRST_ADMIN_PASSWORD" FIRST_ADMIN_PASSWORD "" secret

echo ""
echo "--- Sound-selection policy ---"
echo "Use core.predict.stable_preference_predictor to enable the demo algorithm."
prompt_optional "COSOUND_CORE_PREDICTOR" COSOUND_CORE_PREDICTOR "core.predict.random_predictor"
prompt_optional "COSOUND_MIN_LAYERS" COSOUND_MIN_LAYERS "1"
prompt_optional "COSOUND_MAX_LAYERS" COSOUND_MAX_LAYERS "3"
prompt_optional "COSOUND_ACTIVE_LISTENER_MINUTES" COSOUND_ACTIVE_LISTENER_MINUTES "5"
prompt_optional "COSOUND_MINIMUM_HOLD_SECONDS" COSOUND_MINIMUM_HOLD_SECONDS "120"
prompt_optional "COSOUND_MAX_STAY_SECONDS (blank means indefinite)" COSOUND_MAX_STAY_SECONDS ""
prompt_optional "COSOUND_DISAGREEMENT_PENALTY" COSOUND_DISAGREEMENT_PENALTY "0.25"
prompt_optional "COSOUND_EXPLORATION_PROBABILITY" COSOUND_EXPLORATION_PROBABILITY "0"
prompt_optional "COSOUND_EXPLORATION_SIZE" COSOUND_EXPLORATION_SIZE "5"
prompt_optional "COSOUND_HOUSE_SOUND_ID" COSOUND_HOUSE_SOUND_ID "5"

# ── write file ────────────────────────────────────────────────────────────────

cat > "$ENV_FILE" <<EOF
# Generated by bin/setup_env.sh — do not commit.

# --- Django ---
SECRET_KEY=${SECRET_KEY}
DEBUG=False
SITE_ADDRESS=${SITE_ADDRESS}
PROD_HOSTS=${PROD_HOSTS}
WEB_CONCURRENCY=1
VOTE_THROTTLE_SECONDS=60
SERVER_REFRESH_INTERVAL=30

# --- Sound-selection policy ---
COSOUND_CORE_PREDICTOR=${COSOUND_CORE_PREDICTOR}
COSOUND_MIN_LAYERS=${COSOUND_MIN_LAYERS}
COSOUND_MAX_LAYERS=${COSOUND_MAX_LAYERS}
COSOUND_ACTIVE_LISTENER_MINUTES=${COSOUND_ACTIVE_LISTENER_MINUTES}
COSOUND_MINIMUM_HOLD_SECONDS=${COSOUND_MINIMUM_HOLD_SECONDS}
COSOUND_MAX_STAY_SECONDS=${COSOUND_MAX_STAY_SECONDS}
COSOUND_DISAGREEMENT_PENALTY=${COSOUND_DISAGREEMENT_PENALTY}
COSOUND_EXPLORATION_PROBABILITY=${COSOUND_EXPLORATION_PROBABILITY}
COSOUND_EXPLORATION_SIZE=${COSOUND_EXPLORATION_SIZE}
COSOUND_HOUSE_SOUND_ID=${COSOUND_HOUSE_SOUND_ID}

# --- Postgres ---
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
DATABASE_URL=${DATABASE_URL}

# --- AWS ---
AWS_ACCESS_KEY_ID=${AWS_ACCESS_KEY_ID}
AWS_SECRET_ACCESS_KEY=${AWS_SECRET_ACCESS_KEY}
AWS_STORAGE_BUCKET_NAME=${AWS_STORAGE_BUCKET_NAME}
AWS_S3_REGION_NAME=${AWS_S3_REGION_NAME}

# --- First admin ---
FIRST_ADMIN_EMAIL=${FIRST_ADMIN_EMAIL}
FIRST_ADMIN_USERNAME=${FIRST_ADMIN_USERNAME}
FIRST_ADMIN_PASSWORD=${FIRST_ADMIN_PASSWORD}
EOF

chmod 600 "$ENV_FILE"
echo ""
echo "Written to $ENV_FILE (mode 600)."
echo "Run 'make docker-build && make docker-up' to start the stack."
